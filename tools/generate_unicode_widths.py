#!/usr/bin/env python3
"""Generate Braxton's fixed Unicode column-width table from pinned local data.

Inputs (checked in, never fetched by this script):
  tools/unicode/16.0.0/EastAsianWidth.txt
  tools/unicode/16.0.0/emoji-data.txt

Output:
  src/main/java/io/github/dhoard/braxton/internal/text/Unicode16Width.java

Usage:
  python3 tools/generate_unicode_widths.py           # write the table
  python3 tools/generate_unicode_widths.py --check   # verify the table is current

The script uses only the Python standard library and works offline.
"""

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "tools" / "unicode" / "16.0.0"
LICENSE_HEADER = (ROOT / "assets" / "license-header.txt").read_text(encoding="utf-8")

OUTPUT = (ROOT / "src" / "main" / "java" / "io" / "github" / "dhoard" / "braxton"
          / "internal" / "text" / "Unicode16Width.java")

PINNED_SHA256 = {
    "EastAsianWidth.txt": "43adc76c0686a42cb370764eb8cfe2b2a45b10b855e5572a2db4a0eecce15d5b",
    "emoji-data.txt": "f1365a5173eee18e1f98b240cdc492e84a25f1ce7e0c9d1094eb29c41a22696a",
    "LICENSE.txt": "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96",
}

RANGE = re.compile(r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*([A-Za-z_]+)")


def verify_inputs() -> None:
    for name, expected in PINNED_SHA256.items():
        path = DATA / name
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != expected:
            raise SystemExit(f"{path} has changed (sha256 {digest}); update the pin deliberately")


def parse(path: Path, wanted: set[str]) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        match = RANGE.match(line)
        if not match:
            continue
        if match.group(3) not in wanted:
            continue
        start = int(match.group(1), 16)
        end = int(match.group(2) or match.group(1), 16)
        ranges.append((start, end))
    return ranges


def merge(ranges: list[tuple[int, int]]) -> list[tuple[int, int]]:
    merged: list[list[int]] = []
    for start, end in sorted(ranges):
        if merged and start <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], end)
        else:
            merged.append([start, end])
    return [(start, end) for start, end in merged]


def render(ranges: list[tuple[int, int]]) -> str:
    starts = ", ".join(f"0x{start:X}" for start, _ in ranges)
    ends = ", ".join(f"0x{end:X}" for _, end in ranges)
    wrapped_starts = wrap(starts)
    wrapped_ends = wrap(ends)
    return LICENSE_HEADER + f"""package io.github.dhoard.braxton.internal.text;

/**
 * Fixed Unicode 16.0.0 column widths for clusters that occupy two terminal columns.
 *
 * <p>Generated by {{@code tools/generate_unicode_widths.py}} from
 * {{@code tools/unicode/16.0.0/EastAsianWidth.txt}} (East_Asian_Width W and F) and
 * {{@code tools/unicode/16.0.0/emoji-data.txt}} (Emoji_Presentation). Do not edit by hand.</p>
 */
public final class Unicode16Width {{

    private static final int[] START = {{{wrapped_starts}}};

    private static final int[] END = {{{wrapped_ends}}};

    private Unicode16Width() {{}}

    /** Whether the code point is wide by the pinned policy (ignoring variation selectors). */
    public static boolean isWide(int codePoint) {{
        int low = 0;
        int high = START.length - 1;
        while (low <= high) {{
            int mid = (low + high) >>> 1;
            if (codePoint < START[mid]) {{
                high = mid - 1;
            }} else if (codePoint > END[mid]) {{
                low = mid + 1;
            }} else {{
                return true;
            }}
        }}
        return false;
    }}
}}
"""


def wrap(text: str, width: int = 92) -> str:
    lines: list[str] = []
    line = ""
    for token in text.split(", "):
        candidate = token if not line else line + ", " + token
        if len(candidate) > width and line:
            lines.append(line)
            line = token
        else:
            line = candidate
    if line:
        lines.append(line)
    return "\n            " + ",\n            ".join(lines)


def main() -> int:
    verify_inputs()
    wide = parse(DATA / "EastAsianWidth.txt", {"W", "F"})
    emoji = parse(DATA / "emoji-data.txt", {"Emoji_Presentation"})
    ranges = merge(wide + emoji)
    generated = render(ranges)
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != generated:
            print(f"stale: {OUTPUT}", file=sys.stderr)
            return 1
        print(f"ok: {OUTPUT} ({len(ranges)} wide ranges)")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(ranges)} wide ranges)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
