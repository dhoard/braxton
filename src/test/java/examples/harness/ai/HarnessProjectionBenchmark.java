package examples.harness.ai;

import io.github.dhoard.braxton.layout.Size;
import java.util.Collections;
import java.util.List;
import java.util.concurrent.TimeUnit;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Param;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.Warmup;

/** Application projection is measured separately from indexed ScrollView frame work. */
@State(Scope.Thread)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Warmup(iterations = 3, time = 1)
@Measurement(iterations = 5, time = 1)
@Fork(2)
public class HarnessProjectionBenchmark {
    @Param({"10", "200"})
    public int entries;

    private Harness.Model model;

    @Setup
    public void setup() {
        model = Harness.Model.initial(new Size(24, 80), "probe", List.of())
                .withEntries(Collections.nCopies(entries, new HarnessEntry.Assistant("word ".repeat(200))));
    }

    @Benchmark
    public Object projectWindow() {
        return HarnessProjection.window(
                model.session(), 80, HarnessProjection.layout(model).body());
    }
}
